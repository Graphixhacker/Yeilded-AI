import { jsPDF } from 'jspdf';

export interface DocumentExportOptions {
  title: string;
  country: string;
  committee: string;
  topic?: string;
  type: 'Position Paper' | 'Speech' | 'Draft Resolution' | 'Crisis Directive' | 'Policy Briefing';
  content: string;
}

export function exportDocumentToPDF(options: DocumentExportOptions): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 20;
  const contentWidth = pageWidth - margin * 2;

  // Header Banner - UN Navy with Gold Accent
  doc.setFillColor(11, 31, 58); // #0B1F3A
  doc.rect(0, 0, pageWidth, 28, 'F');

  doc.setFillColor(212, 175, 55); // #D4AF37 Gold stripe
  doc.rect(0, 27, pageWidth, 1.5, 'F');

  // Title in Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.setTextColor(255, 255, 255);
  doc.text('UNITED NATIONS • MODEL UNITED NATIONS ARCHIVE', margin, 12);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(212, 175, 55);
  doc.text(`OFFICIAL DIPLOMATIC DOCUMENTATION • ${options.type.toUpperCase()}`, margin, 20);

  // Metadata Block
  let cursorY = 38;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.setTextColor(11, 31, 58);
  doc.text(options.title || `${options.country} - ${options.type}`, margin, cursorY);
  cursorY += 8;

  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(80, 80, 80);
  doc.text('DELEGATION:', margin, cursorY);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(20, 20, 20);
  doc.text(options.country, margin + 30, cursorY);
  cursorY += 6;

  doc.setFont('helvetica', 'bold');
  doc.setTextColor(80, 80, 80);
  doc.text('COMMITTEE:', margin, cursorY);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(20, 20, 20);
  doc.text(options.committee, margin + 30, cursorY);
  cursorY += 6;

  if (options.topic) {
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(80, 80, 80);
    doc.text('AGENDA ITEM:', margin, cursorY);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(20, 20, 20);
    const topicLines = doc.splitTextToSize(options.topic, contentWidth - 30);
    doc.text(topicLines, margin + 30, cursorY);
    cursorY += (topicLines.length * 5) + 2;
  }

  // Thin line below metadata
  doc.setDrawColor(200, 200, 200);
  doc.line(margin, cursorY, pageWidth - margin, cursorY);
  cursorY += 8;

  // Body text formatting
  doc.setFont('times', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(25, 25, 25);

  // Strip Markdown hashes and asterisks for clean PDF rendering
  const cleanedText = options.content
    .replace(/^#+\s*(.*)$/gm, '\n$1\n')
    .replace(/\*\*(.*?)\*\*/g, '$1')
    .replace(/\*(.*?)\*/g, '$1');

  const lines = doc.splitTextToSize(cleanedText, contentWidth);

  for (let i = 0; i < lines.length; i++) {
    if (cursorY > pageHeight - 20) {
      doc.addPage();
      // Add page header
      doc.setFillColor(11, 31, 58);
      doc.rect(0, 0, pageWidth, 8, 'F');
      cursorY = 20;
    }
    const line = lines[i];
    // Check if it's a section header
    if (line.match(/^[I|V|X]+\.\s+/i) || line.includes('DELEGATION POSITION PAPER')) {
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(11, 31, 58);
      doc.text(line, margin, cursorY);
      doc.setFont('times', 'normal');
      doc.setTextColor(25, 25, 25);
    } else {
      doc.text(line, margin, cursorY);
    }
    cursorY += 5.2;
  }

  // Footer on final page
  const totalPages = doc.getNumberOfPages();
  for (let p = 1; p <= totalPages; p++) {
    doc.setPage(p);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(130, 130, 130);
    doc.text(
      `Generated by Yeilded • Page ${p} of ${totalPages}`,
      pageWidth / 2,
      pageHeight - 8,
      { align: 'center' }
    );
  }

  const filename = `${options.country}_${options.committee}_${options.type.replace(/\s+/g, '_')}.pdf`;
  doc.save(filename);
}

export function exportDocumentToWord(options: DocumentExportOptions): void {
  const header = `UNITED NATIONS - MODEL UNITED NATIONS
DELEGATION: ${options.country}
COMMITTEE: ${options.committee}
AGENDA ITEM: ${options.topic || 'General Debate'}
DOCUMENT: ${options.type.toUpperCase()}
DATE: ${new Date().toLocaleDateString()}
============================================================\n\n`;

  const fullText = header + options.content;
  const blob = new Blob([fullText], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${options.country}_${options.type.replace(/\s+/g, '_')}.txt`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export async function copyToClipboard(text: string): Promise<boolean> {
  if (navigator?.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // Fall through to execCommand
    }
  }
  try {
    const textarea = document.createElement('textarea');
    textarea.value = text;
    textarea.style.position = 'fixed';
    textarea.style.left = '-9999px';
    textarea.style.top = '-9999px';
    textarea.style.opacity = '0';
    textarea.setAttribute('readonly', '');
    document.body.appendChild(textarea);
    textarea.focus();
    textarea.select();
    textarea.setSelectionRange(0, textarea.value.length);
    const success = document.execCommand('copy');
    document.body.removeChild(textarea);
    return success;
  } catch (err) {
    console.error('Failed to copy to clipboard:', err);
    return false;
  }
}
